async function cached(key, ttl, fn) {
  const hit = cache.get(key);
  if (hit && Date.now() - hit.time < ttl) return hit.value;
  const value = await fn();
  cache.set(key, { time: Date.now(), value });
  return value;
}

async function fetchText(url, options = {}) {
  const controller = new AbortController();
  const timeoutMs = num(options.timeout, 15000);
  const timer = setTimeout(() => controller.abort(), timeoutMs);
  const { timeout, signal: callerSignal, ...rest } = options;
  if (callerSignal?.aborted) controller.abort();
  try {
    const r = await fetchImpl(url, {
      ...rest,
      signal: controller.signal,
      headers: {
        "User-Agent": "Mozilla/5.0 ALI-Flow-Radar/5.13.0",
        Accept: "text/html,text/plain,text/csv,application/json,*/*",
        ...(options.headers || {})
      }
    });
    const text = await r.text();
    if (!r.ok) throw new Error(`HTTP ${r.status}: ${text.slice(0, 140)}`);
    return text;
  } finally {
    clearTimeout(timer);
  }
}

async function fetchJson(url, options = {}) {
  const text = await fetchText(url, options);
  try {
    return JSON.parse(text);
  } catch {
    throw new Error("Invalid JSON response");
  }
}

